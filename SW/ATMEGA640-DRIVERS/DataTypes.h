#ifndef DATA_TYPES_H_
#define DATA_TYPES_H_

typedef unsigned char       DT_uint8_t;
typedef signed char         DT_int8_t;

typedef unsigned short      DT_uint16_t;
typedef signed short        DT_int16_t;

typedef unsigned long       DT_uint32_t;
typedef signed long         DT_int32_t;

typedef unsigned long long  DT_uint64_t;
typedef signed long long    DT_int64_t;

typedef unsigned char       DT_bool_t;

#define DT_TRUE    1
#define DT_FALSE   0

#endif /* DATA_TYPES_H_ */